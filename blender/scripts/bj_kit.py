def collection(name: str, parent=None):
    col = bpy.data.collections.get(name)
    if col is None:
        col = bpy.data.collections.new(name)
        (parent or bpy.context.scene.collection).children.link(col)
    return col


def empty(name: str, loc: Vector = Vector((0, 0, 0)), parent=None, col=None, props: dict | None = None,
          display: str = 'PLAIN_AXES', size: float = 0.3):
    obj = bpy.data.objects.new(name, None)
    obj.empty_display_type = display
    obj.empty_display_size = size
    (col or bpy.context.scene.collection).objects.link(obj)
    if parent is not None:
        obj.parent = parent
        obj.location = loc - world_loc(parent)
    else:
        obj.location = loc
    for k, v in (props or {}).items():
        obj[k] = v
    return obj


def world_loc(obj) -> Vector:
    loc = Vector(obj.location)
    p = obj.parent
    while p is not None:
        loc += Vector(p.location)
        p = p.parent
    return loc


def set_props(obj, **props):
    for k, v in props.items():
        obj['bj_' + k] = v
    return obj

