def W(x: float, z: float, y: float = 0.0) -> Vector:
    """Grid position (x east, z south, y up) → Blender world vector."""
    return Vector((x - GRID_W / 2, GRID_H / 2 - z, y))


def WT(x: int, z: int, y: float = 0.0) -> Vector:
    """Centre of tile (x, z)."""
    return W(x + 0.5, z + 0.5, y)


def to_three(v: Vector) -> list:
    """Blender vector → Three.js world coordinates (x, y, z)."""
    return [round(v.x, 4), round(v.z, 4), round(-v.y, 4)]

