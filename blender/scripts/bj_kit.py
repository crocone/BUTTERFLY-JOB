def rot_z(deg: float, about: Vector | None = None) -> Matrix:
    m = Matrix.Rotation(math.radians(deg), 4, 'Z')
    if about is None:
        return m
    return Matrix.Translation(about) @ m @ Matrix.Translation(-Vector(about))


def translate(v: Vector) -> Matrix:
    return Matrix.Translation(Vector(v))

