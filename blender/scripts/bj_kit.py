def save_and_export(asset: str, notes: str = ''):
    os.makedirs(SRC_DIR, exist_ok=True)
    os.makedirs(GLB_DIR, exist_ok=True)
    os.makedirs(MANIFEST_PARTS_DIR, exist_ok=True)
    blend_path = os.path.join(SRC_DIR, f'{asset}.blend')
    glb_path = os.path.join(GLB_DIR, f'{asset}.glb')
    bpy.context.scene['bj_asset'] = asset
    bpy.context.scene['bj_notes'] = notes
    try:
        bpy.ops.file.pack_all()
    except Exception as exc:  # pragma: no cover - diagnostics only
        print('pack_all failed:', exc)
    bpy.ops.wm.save_as_mainfile(filepath=blend_path, compress=True)
