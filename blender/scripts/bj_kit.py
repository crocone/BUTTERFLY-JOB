def text_mb(text: str, size: float, depth: float, col, mat='paper', bold=True, align='CENTER',
            spacing: float = 1.0) -> MB:
    """Returns an MB with extruded letters laid out on the XZ plane (reading along +X, facing -Y),
    baseline at z=0, centred on x=0."""
    curve = bpy.data.curves.new('tmp_text', type='FONT')
    curve.body = text
    curve.font = font(bold)
    curve.size = size
    curve.extrude = depth / 2
    curve.resolution_u = 2
    curve.align_x = align
    curve.space_character = spacing
    curve.fill_mode = 'BOTH'
    obj = bpy.data.objects.new('tmp_text', curve)
    bpy.context.scene.collection.objects.link(obj)
    dg = bpy.context.evaluated_depsgraph_get()
    me = bpy.data.meshes.new_from_object(obj.evaluated_get(dg))
    bm = bmesh.new()
    bm.from_mesh(me)
    rot = Matrix.Rotation(math.pi / 2, 4, 'X')   # text XY plane → XZ plane, facing -Y
    bm.transform(rot)
    mb = MB(jitter=0)
    for f in bm.faces:
        pts = [v.co.copy() for v in f.verts]
        if abs(f.normal.y) > 0.5:
            mb.face(pts, mat, col, vary=False)
        else:
            mb.face(pts, 'edge', PAL['card'], vary=False)
    bm.free()
    bpy.data.objects.remove(obj)
    bpy.data.curves.remove(curve)
    bpy.data.meshes.remove(me)
    return mb

