class MB:
    """Accumulates flat-shaded faces with material, per-face colour and UVs."""

    def __init__(self, seed: int = 1, jitter: float = 0.035):
        self.verts: list = []
        self.faces: list = []   # (vertex indices, material key, rgb, uvs|None)
        self.rng = random.Random(seed)
        self.jitter = jitter

    # -- primitive faces ------------------------------------------------------------------
    def face(self, pts: Sequence, mat: str, col, uvs=None, vary: bool = True):
        base = len(self.verts)
        self.verts.extend(tuple(p) for p in pts)
        c = tuple(col)
        if vary and self.jitter > 0:
            k = 1.0 + (self.rng.random() - 0.5) * 2 * self.jitter
            c = tuple(min(1.0, max(0.0, ch * k)) for ch in c)
        self.faces.append((list(range(base, base + len(pts))), mat, c, uvs))
        return self

    def quad(self, a, b, c, d, mat, col, uvs=None, vary=True):
        return self.face([a, b, c, d], mat, col, uvs, vary)

    def merge(self, other: 'MB', matrix: Matrix | None = None):
        base = len(self.verts)
        for v in other.verts:
            self.verts.append(tuple(matrix @ Vector(v)) if matrix is not None else v)
        for idx, mat, col, uvs in other.faces:
            self.faces.append(([i + base for i in idx], mat, col, uvs))
        return self

    def transformed(self, matrix: Matrix) -> 'MB':
        out = MB(jitter=0)
        out.merge(self, matrix)
        return out

    # -- solids ---------------------------------------------------------------------------
    def box(self, x0, y0, z0, x1, y1, z1, mat, col, edge: str | None = 'edge', edge_col=None,
            skip: Iterable[str] = ()):
        """Axis-aligned box in Blender coords.  The thinnest axis is treated as the paper
        thickness: the two faces across it use `mat`, the four cut faces use the cardboard edge."""
        x0, x1 = min(x0, x1), max(x0, x1)
        y0, y1 = min(y0, y1), max(y0, y1)
        z0, z1 = min(z0, z1), max(z0, z1)
        dims = (x1 - x0, y1 - y0, z1 - z0)
        thin = dims.index(min(dims))
        edge_col = edge_col or PAL['card']
        P = lambda x, y, z: (x, y, z)
        faces = {
            '+z': [P(x0, y0, z1), P(x1, y0, z1), P(x1, y1, z1), P(x0, y1, z1)],
            '-z': [P(x0, y1, z0), P(x1, y1, z0), P(x1, y0, z0), P(x0, y0, z0)],
            '+x': [P(x1, y0, z0), P(x1, y1, z0), P(x1, y1, z1), P(x1, y0, z1)],
            '-x': [P(x0, y1, z0), P(x0, y0, z0), P(x0, y0, z1), P(x0, y1, z1)],
            '+y': [P(x1, y1, z0), P(x0, y1, z0), P(x0, y1, z1), P(x1, y1, z1)],
            '-y': [P(x0, y0, z0), P(x1, y0, z0), P(x1, y0, z1), P(x0, y0, z1)],
        }
        axis_of = {'+x': 0, '-x': 0, '+y': 1, '-y': 1, '+z': 2, '-z': 2}
        for key, pts in faces.items():
            if key in skip:
                continue
            if edge is None or axis_of[key] == thin or min(dims) > 0.35:
                self.face(pts, mat, col)
            else:
                self.face(pts, edge, edge_col, uvs=_edge_uvs(pts, thin, (x0, y0, z0), dims))
        return self

    def panel(self, origin: Vector, u: Vector, v: Vector, thickness: float, mat: str, col,
              back_mat: str | None = None, back_col=None, edge: str = 'edge', edge_col=None):
        """Arbitrarily oriented paper panel: parallelogram origin+u+v extruded by `thickness`
        along -normal.  Front uses `mat`, back `back_mat`, the rim uses the cardboard edge."""
        n = u.cross(v).normalized()
        o = Vector(origin)
        a, b, c, d = o, o + u, o + u + v, o + v
        off = -n * thickness
        a2, b2, c2, d2 = a + off, b + off, c + off, d + off
        uu, vv = u.length, v.length
        s = MATS[mat]['uv']
        self.face([a, b, c, d], mat, col, uvs=[(0, 0), (uu * s, 0), (uu * s, vv * s), (0, vv * s)])
        bm_ = back_mat or mat
        sb = MATS[bm_]['uv']
        self.face([b2, a2, d2, c2], bm_, back_col or col,
                  uvs=[(uu * sb, 0), (0, 0), (0, vv * sb), (uu * sb, vv * sb)])
        ec = edge_col or PAL['card']
        for p, q, L in ((a, b, uu), (b, c, vv), (c, d, uu), (d, a, vv)):
            self.face([p, q, q + off, p + off], edge, ec, uvs=[(0, 0), (L, 0), (L, 1), (0, 1)])
        return self

    def prism(self, pts2d: Sequence, z0: float, z1: float, mat: str, col, side_mat=None, side_col=None,
              cap_top=True, cap_bottom=True):
        """Vertical extrusion of a convex/concave polygon (counter-clockwise, Blender XY)."""
        top = [(x, y, z1) for x, y in pts2d]
        bot = [(x, y, z0) for x, y in pts2d]
        if cap_top:
            self.face(top, mat, col)
        if cap_bottom:
            self.face(list(reversed(bot)), mat, col)
        sm = side_mat or mat
        sc = side_col or col
        n = len(pts2d)
        for i in range(n):
            j = (i + 1) % n
            self.face([bot[i], bot[j], top[j], top[i]], sm, sc)
        return self

    def cylinder(self, centre: Vector, r0: float, r1: float, h: float, sides: int, mat: str, col,
                 cap=True, rot: float = 0.0, cap_col=None):
        c = Vector(centre)
        ring0 = [c + Vector((math.cos(rot + i / sides * 2 * math.pi) * r0,
                             math.sin(rot + i / sides * 2 * math.pi) * r0, 0)) for i in range(sides)]
        ring1 = [c + Vector((math.cos(rot + i / sides * 2 * math.pi) * r1,
                             math.sin(rot + i / sides * 2 * math.pi) * r1, h)) for i in range(sides)]
        for i in range(sides):
            j = (i + 1) % sides
            self.face([ring0[i], ring0[j], ring1[j], ring1[i]], mat, col)
        if cap:
            self.face(ring1, mat, cap_col or col)
            self.face(list(reversed(ring0)), mat, cap_col or col)
        return self

    def blob(self, centre: Vector, radius: Vector, mat: str, cols: Sequence, subdiv: int = 1,
             seed: int = 0, rough: float = 0.16, flat_bottom: float | None = None):
        """Faceted low-poly foliage cluster (jittered icosphere)."""
        rng = random.Random(seed)
        bm = bmesh.new()
        bmesh.ops.create_icosphere(bm, subdivisions=subdiv, radius=1.0)
        for v in bm.verts:
            d = 1.0 + (rng.random() - 0.5) * 2 * rough
            v.co = Vector((v.co.x * radius.x * d, v.co.y * radius.y * d, v.co.z * radius.z * d))
            if flat_bottom is not None and v.co.z < -radius.z * flat_bottom:
                v.co.z = -radius.z * flat_bottom + (v.co.z + radius.z * flat_bottom) * 0.25
        for f in bm.faces:
            pts = [Vector(centre) + v.co for v in f.verts]
            # lighter facets on top, darker below: printed imperfection
            up = f.normal.z
            col = cols[rng.randrange(len(cols))]
            shade = 1.0 + 0.06 * up
            self.face(pts, mat, tuple(min(1.0, ch * shade) for ch in col))
        bm.free()
        return self

    def wall(self, p0: Vector, p1: Vector, z0: float, z1: float, thickness: float,
             holes: Sequence = (), out_mat='wall', out_col=None, in_mat='paper', in_col=None,
             edge_col=None, centered=True, reveal_col=None):
        """Wall from p0 to p1 (Blender XY, horizontal) between heights z0..z1.
        Outside face is on the right of p0→p1 (i.e. -normal side where normal = up × dir).
        holes: (u0, u1, v0, v1) in metres along the wall (u) and up from z0 (v)."""
        p0 = Vector((p0.x, p0.y, 0))
        p1 = Vector((p1.x, p1.y, 0))
        d = (p1 - p0)
        L = d.length
        dn = d.normalized()
        right = Vector((dn.y, -dn.x, 0))   # outside direction
        H = z1 - z0
        t = thickness
        o_off = right * (t / 2 if centered else t)
        i_off = -right * (t / 2 if centered else 0)
        out_col = out_col or PAL['cream']
        in_col = in_col or PAL['ivory']
        edge_col = edge_col or PAL['card']
        reveal_col = reveal_col or edge_col
        us = sorted({0.0, L} | {h[0] for h in holes} | {h[1] for h in holes})
        vs = sorted({0.0, H} | {h[2] for h in holes} | {h[3] for h in holes})

        def inside_hole(u, v):
            return any(h[0] <= u <= h[1] and h[2] <= v <= h[3] for h in holes)

        def P(u, v, side):
            base = p0 + dn * u + Vector((0, 0, z0 + v))
            return base + (o_off if side == 'o' else i_off)

        so = MATS[out_mat]['uv']
        si = MATS[in_mat]['uv']
        for a in range(len(us) - 1):
            for b in range(len(vs) - 1):
                u0, u1, v0, v1 = us[a], us[a + 1], vs[b], vs[b + 1]
                if inside_hole((u0 + u1) / 2, (v0 + v1) / 2):
                    continue
                # outside face (facing `right`)
                self.face([P(u1, v0, 'o'), P(u0, v0, 'o'), P(u0, v1, 'o'), P(u1, v1, 'o')], out_mat, out_col,
                          uvs=[(-u1 * so, (z0 + v0) * so), (-u0 * so, (z0 + v0) * so),
                               (-u0 * so, (z0 + v1) * so), (-u1 * so, (z0 + v1) * so)])
                self.face([P(u0, v0, 'i'), P(u1, v0, 'i'), P(u1, v1, 'i'), P(u0, v1, 'i')], in_mat, in_col,
                          uvs=[(u0 * si, (z0 + v0) * si), (u1 * si, (z0 + v0) * si),
                               (u1 * si, (z0 + v1) * si), (u0 * si, (z0 + v1) * si)])
        # rim: top, bottom, ends
        def rim(pa, pb, L_):
            self.face([pa[0], pb[0], pb[1], pa[1]], 'edge', edge_col,
                      uvs=[(0, 0), (L_, 0), (L_, 1), (0, 1)])
        # top edge (split around holes touching the top)
        top_segments = _segments(0, L, [(h[0], h[1]) for h in holes if h[3] >= H - 1e-6])
        for s0, s1 in top_segments:
            rim((P(s1, H, 'i'), P(s1, H, 'o')), (P(s0, H, 'i'), P(s0, H, 'o')), s1 - s0)
        bot_segments = _segments(0, L, [(h[0], h[1]) for h in holes if h[2] <= 1e-6])
        for s0, s1 in bot_segments:
            rim((P(s0, 0, 'i'), P(s0, 0, 'o')), (P(s1, 0, 'i'), P(s1, 0, 'o')), s1 - s0)
        self.face([P(0, 0, 'o'), P(0, 0, 'i'), P(0, H, 'i'), P(0, H, 'o')], 'edge', edge_col,
                  uvs=[(0, 0), (0, 1), (H, 1), (H, 0)])
        self.face([P(L, 0, 'i'), P(L, 0, 'o'), P(L, H, 'o'), P(L, H, 'i')], 'edge', edge_col,
                  uvs=[(0, 1), (0, 0), (H, 0), (H, 1)])
        # hole reveals
        for u0, u1, v0, v1 in holes:
            if v0 > 1e-6:   # sill
                self.face([P(u0, v0, 'o'), P(u1, v0, 'o'), P(u1, v0, 'i'), P(u0, v0, 'i')], 'edge', reveal_col,
                          uvs=[(0, 0), (u1 - u0, 0), (u1 - u0, 1), (0, 1)])
            if v1 < H - 1e-6:  # head
                self.face([P(u0, v1, 'i'), P(u1, v1, 'i'), P(u1, v1, 'o'), P(u0, v1, 'o')], 'edge', reveal_col,
                          uvs=[(0, 1), (u1 - u0, 1), (u1 - u0, 0), (0, 0)])
            self.face([P(u0, v0, 'i'), P(u0, v0, 'o'), P(u0, v1, 'o'), P(u0, v1, 'i')], 'edge', reveal_col,
                      uvs=[(0, 1), (0, 0), (v1 - v0, 0), (v1 - v0, 1)])
            self.face([P(u1, v0, 'o'), P(u1, v0, 'i'), P(u1, v1, 'i'), P(u1, v1, 'o')], 'edge', reveal_col,
                      uvs=[(0, 0), (0, 1), (v1 - v0, 1), (v1 - v0, 0)])
        return self

    # -- output -----------------------------------------------------------------------------
    def build(self, name: str, pivot: Vector | None = None, parent=None, col=None, props: dict | None = None):
        if not self.faces:
            obj = empty(name, pivot if pivot is not None else Vector((0, 0, 0)), parent=parent, col=col, props=props)
            return obj
        pivot = Vector(pivot) if pivot is not None else Vector((0, 0, 0))
        mesh = bpy.data.meshes.new(name)
        verts = [(v[0] - pivot.x, v[1] - pivot.y, v[2] - pivot.z) for v in self.verts]
        faces = [f[0] for f in self.faces]
        mesh.from_pydata(verts, [], faces)
        mesh.update(calc_edges=True)
        mat_keys = []
        for f in self.faces:
            if f[1] not in mat_keys:
                mat_keys.append(f[1])
        for k in mat_keys:
            mesh.materials.append(material(k))
        mesh.polygons.foreach_set('material_index', [mat_keys.index(f[1]) for f in self.faces])
        mesh.polygons.foreach_set('use_smooth', [False] * len(self.faces))
        # per-corner colour + uv
        colors = []
        uvs = []
        for idx, mat, rgb, fuv in self.faces:
            pts = [self.verts[i] for i in idx]
            if fuv is None:
                fuv = _box_uvs(pts, MATS[mat]['uv'])
            for k in range(len(idx)):
                colors.extend((rgb[0], rgb[1], rgb[2], 1.0))
                uvs.extend(fuv[k])
        ca = mesh.color_attributes.new(name='Col', type='BYTE_COLOR', domain='CORNER')
        ca.data.foreach_set('color_srgb', colors)
        mesh.color_attributes.active_color = ca
        mesh.color_attributes.render_color_index = 0
        uvl = mesh.uv_layers.new(name='UVMap')
        uvl.uv.foreach_set('vector', uvs)
        mesh.validate(clean_customdata=False)
        obj = bpy.data.objects.new(name, mesh)
        (col or bpy.context.scene.collection).objects.link(obj)
        if parent is not None:
            obj.parent = parent
            obj.location = pivot - world_loc(parent)
        else:
            obj.location = pivot
        for k, v in (props or {}).items():
            obj[k] = v
        return obj


def _segments(a, b, cuts):
    """Split [a,b] removing the given (c0,c1) intervals."""
    out = [(a, b)]
    for c0, c1 in cuts:
        nxt = []
        for s0, s1 in out:
            if c1 <= s0 or c0 >= s1:
                nxt.append((s0, s1))
                continue
            if c0 > s0:
                nxt.append((s0, c0))
            if c1 < s1:
                nxt.append((c1, s1))
        out = nxt
    return [s for s in out if s[1] - s[0] > 1e-6]


def _box_uvs(pts, scale):
    a, b, c = Vector(pts[0]), Vector(pts[1]), Vector(pts[2])
    n = (b - a).cross(c - a)
    ax = max(range(3), key=lambda i: abs(n[i]))
    out = []
    for p in pts:
        if ax == 2:
            out.append((p[0] * scale, p[1] * scale))
        elif ax == 0:
            out.append((p[1] * scale * (1 if n[0] > 0 else -1), p[2] * scale))
        else:
            out.append((p[0] * scale * (-1 if n[1] > 0 else 1), p[2] * scale))
    return out


def _edge_uvs(pts, thin_axis, lo, dims):
    """Cardboard edge: V spans the paper thickness 0..1, U runs along the edge (metres)."""
    out = []
    t = dims[thin_axis] or 1.0
    for p in pts:
        v = (p[thin_axis] - lo[thin_axis]) / t
        # along = largest remaining axis coordinate
        others = [i for i in range(3) if i != thin_axis]
        along = max(others, key=lambda i: dims[i])
        out.append((p[along], v))
    return out

