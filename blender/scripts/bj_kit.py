"""BUTTERFLY JOB — shared Blender asset kit.

Runs inside Blender 5.0.x (tested with the official `bpy` 5.0.1 module in background mode and
compatible with `blender -b -P <script>`).  Every visible 3D object of the game is generated by
functions in this package, saved as an editable .blend file and exported as a .glb.

Conventions
-----------
* 1 Blender unit = 1 game tile = 1 m.  Blender is Z-up; the glTF exporter converts to Y-up.
* Grid coordinates (x east, z south) map to Blender as  X = x - 15,  Y = 11 - z,  Z = height.
  Three.js therefore sees  X = x - 15,  Z = z - 11,  Y = height.
* Node names use `<asset>__<part>` (double underscore) because Three.js strips dots from names.
* Custom properties prefixed `bj_` are exported as glTF extras and summarised in the manifest:
  bj_role     variant | part | anchor | proxy | camera | dynamic | pivot
  bj_variant  stable variant id (conditions live in src/data/variants.json)
  bj_anim     transition style used by the runtime (fold, rise, unfurl, pop, flatten, none)
* Paper look: faces carry a vertex colour (palette + slight printed imperfection) multiplied with a
  tiling grey-scale print texture (grain, hatching, bricks, shingles, paving, cardboard edge).
"""
