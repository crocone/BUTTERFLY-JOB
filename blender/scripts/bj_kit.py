TEX_SIZE = 256


def _noise(size, scale, rng):
    """Tileable value noise via random low-res grid + bilinear upsample (wraps)."""
    n = max(2, size // scale)
    g = rng.random((n, n))
    xs = np.arange(size) * n / size
    x0 = np.floor(xs).astype(int) % n
    x1 = (x0 + 1) % n
    t = xs - np.floor(xs)
    t = t * t * (3 - 2 * t)
    a = g[x0][:, x0] * (1 - t)[None, :] + g[x0][:, x1] * t[None, :]
    b = g[x1][:, x0] * (1 - t)[None, :] + g[x1][:, x1] * t[None, :]
    return a * (1 - t)[:, None] + b * t[:, None]


def _paper_base(rng, size=TEX_SIZE, strength=1.0):
    img = np.ones((size, size), dtype=np.float32)
    img -= 0.035 * strength * _noise(size, 64, rng)
    img -= 0.030 * strength * _noise(size, 16, rng)
    img -= 0.020 * strength * _noise(size, 4, rng)
    # fibres: short random strokes
    for _ in range(int(140 * strength)):
        x, y = rng.integers(0, size, 2)
        ang = rng.random() * math.pi
        ln = rng.integers(4, 14)
        for i in range(ln):
            px = int(x + math.cos(ang) * i) % size
            py = int(y + math.sin(ang) * i) % size
            img[py, px] -= 0.045
    return img


def _draw_hline(img, y, thick, value, x0=0, x1=None):
    size = img.shape[0]
    x1 = size if x1 is None else x1
    for t in range(thick):
        yy = (y + t) % size
        img[yy, x0:x1] = np.minimum(img[yy, x0:x1], value)


def _draw_vline(img, x, thick, value, y0=0, y1=None):
    size = img.shape[0]
    y1 = size if y1 is None else y1
    for t in range(thick):
        xx = (x + t) % size
        img[y0:y1, xx] = np.minimum(img[y0:y1, xx], value)


def _make_texture(kind: str):
    rng = np.random.default_rng(sum(map(ord, kind)) * 7919)  # deterministic per texture kind
    s = TEX_SIZE
    img = _paper_base(rng)
    if kind == 'grain':
        pass
    elif kind == 'hatch':
        # fine diagonal façade hatching with printed irregularities
        for i in range(0, s * 2, 9):
            wob = rng.integers(-1, 2)
            for y in range(s):
                x = (i - y + wob) % s
                if rng.random() > 0.08:
                    img[y, x] = min(img[y, x], 0.86 + rng.random() * 0.04)
    elif kind == 'brick':
        course = 16
        for row, y in enumerate(range(0, s, course)):
            _draw_hline(img, y, 2, 0.80 + rng.random() * 0.05)
            off = 0 if row % 2 == 0 else 16
            for x in range(off, s + 32, 32):
                _draw_vline(img, x % s, 2, 0.82 + rng.random() * 0.05, y, min(s, y + course))
    elif kind == 'roof':
        course = 21
        for row, y in enumerate(range(0, s, course)):
            _draw_hline(img, y, 2, 0.74 + rng.random() * 0.05)
            off = 0 if row % 2 == 0 else 13
            for x in range(off, s + 26, 26):
                _draw_vline(img, x % s, 1, 0.80, y, min(s, y + course))
            # shading under each course
            for t in range(2, 6):
                img[(y + t) % s, :] *= 0.985
    elif kind == 'paving':
        cell = 32
        for y in range(0, s, cell):
            _draw_hline(img, y, 2, 0.80 + rng.random() * 0.04)
            off = 0 if (y // cell) % 2 == 0 else cell // 2
            for x in range(off, s + cell, cell):
                _draw_vline(img, x % s, 2, 0.80 + rng.random() * 0.04, y, min(s, y + cell))
    elif kind == 'cobble':
        cell = 21
        for y in range(0, s, cell):
            for x in range(0, s, cell):
                cx = x + rng.integers(-3, 4)
                cy = y + rng.integers(-3, 4)
                r = cell * 0.46
                for a in np.linspace(0, 2 * math.pi, 40):
                    px = int(cx + cell / 2 + math.cos(a) * r) % s
                    py = int(cy + cell / 2 + math.sin(a) * r * 0.85) % s
                    img[py, px] = min(img[py, px], 0.78)
    elif kind == 'edge':
        # corrugated cardboard: liner / flutes / liner across V (rows), repeating along U
        img = np.ones((s, s), dtype=np.float32) * 0.97
        img -= 0.03 * _noise(s, 16, rng)
        liner = int(s * 0.22)
        _draw_hline(img, liner, 3, 0.70)
        _draw_hline(img, s - liner - 3, 3, 0.70)
        mid0, mid1 = liner + 3, s - liner - 3
        amp = (mid1 - mid0) / 2 - 3
        centre = (mid0 + mid1) / 2
        for x in range(s):
            y = centre + amp * math.sin(x / s * math.pi * 2 * 8)
            yi = int(y)
            for t in range(-1, 2):
                img[(yi + t) % s, x] = min(img[(yi + t) % s, x], 0.72)
        img[mid0:mid1, :] *= 0.93
    elif kind == 'foliage':
        for _ in range(260):
            x, y = rng.integers(0, s, 2)
            ln = rng.integers(5, 12)
            ang = rng.random() * math.pi
            for i in range(ln):
                px = int(x + math.cos(ang) * i) % s
                py = int(y + math.sin(ang) * i) % s
                img[py, px] = min(img[py, px], 0.84)
    elif kind == 'wood':
        for y in range(0, s, 6):
            wob = rng.random() * 6
            for x in range(s):
                yy = int(y + 2 * math.sin(x / 23 + wob)) % s
                img[yy, x] = min(img[yy, x], 0.86)
    elif kind == 'grass':
        for _ in range(900):
            x, y = rng.integers(0, s, 2)
            for i in range(rng.integers(3, 7)):
                img[(y - i) % s, (x + i // 3) % s] = min(img[(y - i) % s, (x + i // 3) % s], 0.80)
    elif kind == 'plank':
        for y in range(0, s, 32):
            _draw_hline(img, y, 2, 0.78)
            for x in range(int(rng.integers(0, 64)), s, 96):
                _draw_vline(img, x, 2, 0.80, y, min(s, y + 32))
    elif kind == 'glass':
        img = np.ones((s, s), dtype=np.float32)
        img -= 0.05 * _noise(s, 64, rng)
        for i in range(0, s, 64):
            for y in range(s):
                x = (i + y // 2) % s
                for t in range(6):
                    img[y, (x + t) % s] = min(1.0, img[y, (x + t) % s] + 0.02)
    img = np.clip(img, 0, 1)
    rgba = np.ones((s, s, 4), dtype=np.float32)
    rgba[..., 0] = img
    rgba[..., 1] = img
    rgba[..., 2] = img * 0.995
    return rgba


def texture(kind: str):
    if kind in _TEXTURES:
        return _TEXTURES[kind]
    name = f'bj_tex_{kind}'
    img = bpy.data.images.get(name)
    if img is None:
        img = bpy.data.images.new(name, TEX_SIZE, TEX_SIZE, alpha=False)
        img.pixels.foreach_set(_make_texture(kind).ravel())
        img.file_format = 'PNG'
        img.filepath_raw = f'//textures/{name}.png'
        img.pack()
    _TEXTURES[kind] = img
    return img

